import assert from "node:assert/strict";
import { join } from "node:path";

// Runs against the actual packaged extension in the isolated Chrome harness.
export async function runWorkflowRegressions(browser, fixture, existingPopup, output) {
  const results = {};
  const evaluate = (page, source) => browser.evaluate(page, source);
  const waitIdle = page => browser.wait(page, "document.body.dataset.phase === 'idle' && !document.querySelector('#edit-button').disabled");
  const saved = page => browser.wait(page, "document.querySelector('#draft-status').textContent === 'Draft saved locally'");
  const stored = page => evaluate(page, `(async()=>{const {getCapture}=await import('../common/capture-store.js');return getCapture(new URLSearchParams(location.search).get('capture'))})()`);
  const countEditors = page => evaluate(page, `(async()=> (await chrome.tabs.query({})).filter(t=>t.url?.includes('/editor/editor.html')).length)()`);
  const click = (page, id) => evaluate(page, `document.getElementById(${JSON.stringify(id)}).click()`);
  await evaluate(existingPopup, "chrome.storage.local.set({openEditorAfterCapture:true,captureTarget:'page'})");
  const popup = await browser.open(`chrome-extension://${browser.extensionId}/popup/popup.html`, false);
  await browser.wait(popup, "document.documentElement.dataset.koalashotReady === 'true'");
  assert.equal(await evaluate(popup, "(async()=> (await chrome.storage.local.get('openEditorAfterCapture')).openEditorAfterCapture)()"), false);
  await browser.setViewport(popup, 360, 600, 1);
  const layout = page => evaluate(page, `({height:innerHeight,width:innerWidth,scrollWidth:document.documentElement.scrollWidth,footerBottom:document.querySelector('.product-footer').getBoundingClientRect().bottom,saveRight:document.querySelector('#save-button').getBoundingClientRect().right})`);
  results.popupReady = await layout(popup);
  assert.ok(results.popupReady.footerBottom <= 600, JSON.stringify(results.popupReady));
  await browser.captureScreenshot(popup, join(output, "popup-ready.png"));
  await evaluate(popup, "window.originalSet=chrome.storage.local.set;chrome.storage.local.set=()=>{throw new Error('Injected settings failure')};document.querySelector('#capture-target').value='internal';document.querySelector('#capture-target').dispatchEvent(new Event('change'))");
  await browser.wait(popup, "document.querySelector('#settings-status').textContent.includes('could not be saved')");
  assert.equal(await evaluate(popup, "document.querySelector('#capture-target').value"), "page");
  await evaluate(popup, "chrome.storage.local.set=window.originalSet");

  await browser.activate(fixture);
  await evaluate(fixture, "document.head.innerHTML='<title>Workflow regression</title>';document.body.style.cssText='margin:0';document.body.innerHTML='<div style=\"height:100px;background:orange\">One viewport</div>';window.scrollTo(0,0)");
  const editorCount = await countEditors(popup);
  // Explicit failure injection into the OS write boundary, not a hidden retry.
  await evaluate(popup, `window.copyCalls=0;Object.defineProperty(navigator.clipboard,'write',{configurable:true,value:async()=>{window.copyCalls++;throw new Error('Injected clipboard failure')}})`);
  await click(popup, "copy-button");
  await browser.wait(popup, "document.querySelector('#status').textContent.includes('Injected clipboard failure')");
  await waitIdle(popup);
  assert.equal(await countEditors(popup), editorCount);
  results.copyFailure = await evaluate(popup, "document.querySelector('#status').textContent");
  assert.match(results.copyFailure, /Copy failed/);
  assert.equal(await evaluate(popup, "document.querySelector('#cancel-button').hidden"), true);
  await evaluate(popup, "Object.defineProperty(navigator.clipboard,'write',{configurable:true,value:async()=>{window.copyCalls++}})");
  await click(popup, "copy-result-button");
  await browser.wait(popup, "document.querySelector('#status').textContent === 'Full-page screenshot copied.'");
  await waitIdle(popup);
  assert.equal(await countEditors(popup), editorCount);
  await click(popup, "capture-again-button"); await click(popup, "save-button"); await waitIdle(popup);
  assert.equal(await countEditors(popup), editorCount);
  results.popupResult = await layout(popup);
  assert.ok(results.popupResult.footerBottom <= 600, JSON.stringify(results.popupResult));
  await browser.captureScreenshot(popup, join(output, "popup-result.png"));
  await browser.activate(fixture);
  const previousPreview = await evaluate(popup, "document.querySelector('#capture-preview').src");
  await evaluate(popup, "window.originalCapture=chrome.tabs.captureVisibleTab;chrome.tabs.captureVisibleTab=()=>{throw new Error('Injected capture failure')}");
  await click(popup, "capture-again-button"); await click(popup, "save-button");
  await browser.wait(popup, "document.querySelector('#status').textContent.includes('Injected capture failure')");
  await waitIdle(popup);
  assert.equal(await evaluate(popup, "document.querySelector('#capture-preview').src"), previousPreview);
  assert.equal(await evaluate(popup, "document.querySelector('#result-card').hidden"), false);
  await evaluate(popup, "chrome.tabs.captureVisibleTab=window.originalCapture");
  results.burst = await evaluate(popup, `(async()=>{const {captureScreenshot}=await import('./capture-controller.js');const captures=[];for(let i=0;i<4;i++){const r=await captureScreenshot();captures.push(r.blob.size)}return captures})()`);
  assert.ok(results.burst.every(size => size > 0));
  console.log("workflow: distinct capture actions, retained results, rate limits passed");

  const protocol = `(async()=>{const [t]=await chrome.tabs.query({active:true,currentWindow:true});await chrome.scripting.executeScript({target:{tabId:t.id},files:['content/capture-page.js']});const id=crypto.randomUUID();const p=chrome.tabs.connect(t.id,{name:'koalashot-capture:'+id});const req=m=>new Promise(r=>{const f=x=>{p.onMessage.removeListener(f);r(x)};p.onMessage.addListener(f);p.postMessage({...m,sessionId:id})});`;
  results.stalePing = await evaluate(popup, protocol + `await req({type:'start',target:'page'});await req({type:'restore'});const ping=await req({type:'ping'});p.disconnect();return ping})()`);
  assert.equal(results.stalePing.ok, false);
  await evaluate(fixture, "document.body.innerHTML='<div style=\"height:2400px;background:linear-gradient(red,blue)\">Geometry</div>';window.scrollTo(0,0)");
  results.frameChange = await evaluate(popup, `(async()=>{
    const {captureScreenshot}=await import('./capture-controller.js');const original=chrome.tabs.captureVisibleTab;
    chrome.tabs.captureVisibleTab=function(win,opts,cb){chrome.tabs.query({active:true,currentWindow:true}).then(([t])=>chrome.scripting.executeScript({target:{tabId:t.id},func:()=>window.scrollTo(0,scrollY+90)})).then(()=>original.call(chrome.tabs,win,opts,cb))};
    try{await captureScreenshot();return 'resolved'}catch(e){return e.code}finally{chrome.tabs.captureVisibleTab=original}
  })()`);
  assert.equal(results.frameChange, "frame-changed");
  await evaluate(fixture, "document.body.innerHTML='<div style=\"height:100px\">Slow screenshot</div>';window.scrollTo(0,0)");
  results.watchdog = await evaluate(popup, `(async()=>{const {captureScreenshot}=await import('./capture-controller.js');const original=chrome.tabs.captureVisibleTab;let prematureCleanup;
    chrome.tabs.captureVisibleTab=function(win,opts,cb){setTimeout(async()=>{const [t]=await chrome.tabs.query({active:true,currentWindow:true});const [s]=await chrome.scripting.executeScript({target:{tabId:t.id},func:()=>!document.documentElement.classList.contains('koalashot-capturing')});prematureCleanup=s.result;original.call(chrome.tabs,win,opts,cb)},17500)};
    try{const result=await captureScreenshot();return {prematureCleanup,bytes:result.blob.size}}finally{chrome.tabs.captureVisibleTab=original}})()`);
  assert.equal(results.watchdog.prematureCleanup, false);
  assert.ok(results.watchdog.bytes > 0);
  assert.equal(await evaluate(fixture, "document.documentElement.classList.contains('koalashot-capturing')"), false);
  console.log("workflow: live-frame validation and watchdog passed");

  const id = await evaluate(popup, `(async()=>{const {saveCapture,makeCaptureId}=await import('../common/capture-store.js');const c=document.createElement('canvas');c.width=1000;c.height=1800;const ctx=c.getContext('2d');ctx.fillStyle='white';ctx.fillRect(0,0,c.width,c.height);const blob=await new Promise(r=>c.toBlob(r));const id=makeCaptureId();await saveCapture({id,blob,width:1000,height:1800,filename:'workflow.png',createdAt:Date.now(),sourceUrl:'https://example.test',sourceTitle:'Workflow'});return id})()`);
  const editorUrl = `chrome-extension://${browser.extensionId}/editor/editor.html?capture=${id}`;
  const editor = await browser.open(editorUrl, false);
  await browser.wait(editor, "!document.querySelector('#save-button').disabled");
  await browser.setViewport(editor, 1280, 900, 1);
  await evaluate(editor, "window.downloads=[];HTMLAnchorElement.prototype.click=function(){if(this.download)window.downloads.push(this.download)}");
  await browser.draw(editor, "text", [150, 150], [150, 150]);
  await evaluate(editor, "document.querySelector('#text-input').value='Pending text';document.querySelector('#save-button').click()");
  assert.equal(await evaluate(editor, "window.downloads.length"), 0);
  assert.match(await evaluate(editor, "document.querySelector('#status').textContent"), /Apply|apply/);
  await click(editor, "apply-text-button"); await saved(editor);
  await browser.draw(editor, "crop", [100, 100], [500, 400]);
  await click(editor, "save-button");
  assert.equal(await evaluate(editor, "window.downloads.length"), 0);
  await click(editor, "undo-button");
  assert.equal(await evaluate(editor, "document.querySelector('#pending-edits').hidden"), true);
  assert.equal((await stored(editor)).annotations.length, 1);
  await browser.draw(editor, "crop", [100, 100], [500, 400]);
  await evaluate(editor, "window.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}))");
  assert.equal(await evaluate(editor, "document.querySelector('#apply-crop-button').disabled"), true);
  await browser.draw(editor, "rectangle", [100, 100], [300, 250]); await saved(editor);
  const beforeStyles = (await stored(editor)).annotations;
  await evaluate(editor, "document.querySelector('[data-tool=pen]').click();document.querySelector('[data-color=\"#e53935\"]').click()");
  assert.deepEqual((await stored(editor)).annotations, beforeStyles);
  await evaluate(editor, "document.querySelector('[data-tool=pan]').click();const c=document.querySelector('#interaction-canvas');c.focus();c.dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowDown',bubbles:true}))");
  assert.deepEqual((await stored(editor)).annotations, beforeStyles);
  await evaluate(editor, "const b=document.querySelector('#save-button');b.focus();b.dispatchEvent(new KeyboardEvent('keydown',{key:'z',ctrlKey:true,bubbles:true,cancelable:true}))");
  await saved(editor);
  assert.equal((await stored(editor)).annotations.length, 1);
  assert.equal(await evaluate(editor, "document.querySelector('.brand').tagName"), "SPAN");
  await browser.draw(editor, "marker", [200, 200], [200, 200]);
  await evaluate(editor, "document.querySelector('[data-tool=select]').click();document.querySelector('#marker-size').value=35;document.querySelector('#marker-size').dispatchEvent(new Event('input'))");
  await saved(editor);
  assert.equal((await stored(editor)).annotations.at(-1).radius, 35);
  await click(editor, "duplicate-button"); await saved(editor);
  assert.equal((await stored(editor)).annotations.filter(a => a.type === "marker").length, 2);
  await browser.draw(editor, "blur", [200, 200], [350, 350]);
  await evaluate(editor, "document.querySelector('[data-tool=select]').click();document.querySelector('#effect-strength').value=22;document.querySelector('#effect-strength').dispatchEvent(new Event('input'))");
  await saved(editor);
  assert.equal((await stored(editor)).annotations.at(-1).effectStrength, 22);
  assert.equal(await evaluate(editor, "document.querySelector('#color-controls').hidden"), true);
  const shape = (await stored(editor)).annotations.at(-1);
  await evaluate(editor, `(async()=>{const {getCapture}=await import('../common/capture-store.js');const shape=(await getCapture(new URLSearchParams(location.search).get('capture'))).annotations.at(-1),canvas=document.querySelector('#interaction-canvas'),image=document.querySelector('#capture-image'),rect=image.getBoundingClientRect(),scale=rect.width/image.naturalWidth;
    const pointer=(x,y)=>({clientX:rect.left+x*scale,clientY:rect.top+y*scale,bubbles:true,button:0,pointerId:1,pointerType:'mouse',isPrimary:true});
    canvas.dispatchEvent(new PointerEvent('pointerdown',pointer(shape.x+shape.width,shape.y+shape.height)));
    canvas.dispatchEvent(new PointerEvent('pointermove',pointer(shape.x+shape.width+60,shape.y+shape.height+40)));
    canvas.dispatchEvent(new PointerEvent('pointerup',pointer(shape.x+shape.width+60,shape.y+shape.height+40)));
  })()`);
  await saved(editor);
  const resized = (await stored(editor)).annotations.at(-1);
  assert.ok(Math.abs(resized.width - shape.width - 60) < 1 && Math.abs(resized.height - shape.height - 40) < 1);
  await evaluate(editor, "document.querySelector('#export-filename').value='Custom:export.png'");
  await click(editor, "save-button");
  await browser.wait(editor, "window.downloads.length === 1");
  assert.equal(await evaluate(editor, "window.downloads[0]"), "Custom_export.png");
  results.editorLayouts = [];
  for (const width of [390, 901, 960, 1280]) {
    await browser.setViewport(editor, width, 844, 1);
    const row = await layout(editor); results.editorLayouts.push(row);
    assert.ok(row.scrollWidth <= width && row.saveRight <= width && row.footerBottom <= 844, JSON.stringify(row));
    await browser.captureScreenshot(editor, join(output, `editor-${width}.png`));
  }
  console.log("workflow: pending edits, tool semantics, keyboard, controls and layouts passed");

  const second = await browser.open(editorUrl, false);
  await browser.wait(second, "!document.querySelector('#save-button').disabled");
  await browser.setViewport(editor, 1280, 900, 1);
  await browser.draw(editor, "redact", [400, 100], [600, 250]); await saved(editor);
  await browser.wait(second, "!document.querySelector('#draft-conflict').hidden");
  assert.equal(await evaluate(second, "document.querySelector('#save-button').disabled"), true);
  results.conflictCas = await evaluate(second, `(async()=>{const {saveCaptureDraft}=await import('../common/capture-store.js');try{await saveCaptureDraft('${id}',[],null,0);return 'resolved'}catch(e){return e.code}})()`);
  assert.equal(results.conflictCas, "draft-conflict");
  assert.ok((await stored(editor)).annotations.some(a => a.type === "redact"));
  const originalExpiry = (await stored(editor)).createdAt;
  await click(second, "keep-copy-button");
  await browser.wait(second, `!location.href.endsWith(${JSON.stringify(id)}) && !document.querySelector('#save-button').disabled`);
  assert.equal((await stored(second)).createdAt, originalExpiry);
  assert.notEqual((await stored(second)).id, id);
  await evaluate(popup, `(async()=>{const {getCapture,saveCaptureDraft}=await import('../common/capture-store.js');const c=await getCapture('${id}');await saveCaptureDraft('${id}',c.annotations,{x:1,y:1,width:30,height:30},c.revision);const next=await getCapture('${id}');await saveCaptureDraft('${id}',next.annotations,null,next.revision);return (await getCapture('${id}')).crop})()`).then(crop => assert.equal(crop, null));
  await evaluate(popup, `new Promise((resolve,reject)=>{const r=indexedDB.open('koalashot-captures',2);r.onsuccess=()=>{const db=r.result,t=db.transaction('drafts','readwrite');t.objectStore('drafts').put({id:'${id}',annotations:null,crop:null,revision:99});t.oncomplete=()=>{db.close();resolve()};t.onerror=()=>reject(t.error)}})`);
  const damaged = await browser.open(editorUrl, false);
  await browser.wait(damaged, "!document.querySelector('#error-state').hidden");
  assert.equal(await evaluate(damaged, "document.querySelector('#save-button').disabled"), true);
  assert.equal(await evaluate(damaged, "document.querySelector('#recover-original-button').hidden"), false);
  await click(damaged, "recover-original-button");
  await browser.wait(damaged, `!location.href.endsWith(${JSON.stringify(id)}) && !document.querySelector('#save-button').disabled`);
  assert.equal((await stored(damaged)).annotations.length, 0);
  assert.equal((await stored(damaged)).createdAt, originalExpiry);
  await evaluate(second, `new Promise(resolve=>{const r=indexedDB.open('koalashot-captures',2);r.onsuccess=()=>{const db=r.result,t=db.transaction('drafts','readwrite');t.objectStore('drafts').put({id:new URLSearchParams(location.search).get('capture'),annotations:null,crop:null,revision:99});t.oncomplete=()=>{db.close();resolve()}}})`);
  await click(second, "save-button");
  await browser.wait(second, "!document.querySelector('#error-state').hidden && document.querySelector('#status').textContent.includes('Save failed')");
  assert.equal(await evaluate(second, "document.querySelector('#save-button').disabled"), true);
  results.draftSafety = "CAS conflict, separate-copy expiry, crop reset, corrupt-draft refusal and explicit recovery passed";
  console.log("workflow: concurrent and corrupt drafts passed");
  return results;
}
